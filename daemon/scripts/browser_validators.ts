import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { _ } from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { contractValidator } from "../src/operations/validation.ts";
import wire from "../src/protocol/wire.generated.json" with { type: "json" };
import web from "../src/web/schemas.generated.json" with { type: "json" };

export function browserValidators(): Record<string, string> {
  const validator = contractValidator({ source: true, esm: true, formats: _`require("../operations/number_formats.ts").numberFormats` });
  const contracts = {
    ServerMessage: wire.server,
    WebSessionInfo: web.session,
    WebProblem: web.problem,
  };
  const names: Record<string, string> = {};
  for (const [name, schema] of Object.entries(contracts)) {
    validator.addSchema(schema, name);
    names[`valid${name}`] = name;
  }
  return {
    "validators.generated.js": "// Generated by scripts/browser_validators.ts. Do not edit.\n" + standaloneCode(validator, names) + "\n",
    "validators.generated.d.ts": "// Generated by scripts/browser_validators.ts. Do not edit.\n" + Object.keys(contracts).map((name) =>
      `import type { ${name} } from "../protocol/${name}.ts";\nexport declare function valid${name}(value: unknown): value is ${name};\n`,
    ).join(""),
  };
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, "../src/browser");
  await mkdir(root, { recursive: true });
  for (const [name, source] of Object.entries(browserValidators())) {
    const path = resolve(root, name);
    if (process.argv.includes("--write")) await writeFile(path, source);
    else if (await readFile(path, "utf8") !== source) throw new Error(`Stale ${name}; run bun run browser:generate`);
  }
}
