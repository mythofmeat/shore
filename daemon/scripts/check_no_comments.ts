import ts from "typescript";
import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { Glob } from "bun";

if (typeof ts.createSourceFile !== "function") {
  const resolved = Bun.resolveSync("typescript", import.meta.dir);
  console.error(`typescript ${ts.version} at ${resolved} has no compiler API.`);
  console.error(`Run \`bun install\` in daemon/. Without node_modules bun falls back to a`);
  console.error(`globally cached typescript, and 7.x exports only its version from the root.`);
  process.exit(1);
}

const ROOT = join(import.meta.dir, "..");
const ROOTS = [join(ROOT, "src"), join(ROOT, "tests"), join(ROOT, "scripts")];
const CLIENT = join(ROOT, "..", "client");

const CLAP_FILES = new Set(["shore-cli/src/cli.rs", "shore-tui/src/main.rs"]);
const RUST_DIRECTIVE = /^\/\/\s*(SAFETY:|rustfmt|clippy|allow-)/i;

const DIRECTIVE =
  /^(\/\/|\/\*)[\s*]*(@ts-|eslint|biome|prettier|deno-|c8 |v8 |istanbul|#__|@__|<reference|<amd)/;

const GENERATED = /^.{0,200}?\b(generated by|@generated|do not edit)\b/is;

function commentRanges(sf: ts.SourceFile, text: string): ts.CommentRange[] {
  const byPos = new Map<number, ts.CommentRange>();
  const add = (rs: ts.CommentRange[] | undefined) => {
    for (const r of rs ?? []) byPos.set(r.pos, r);
  };
  const walk = (node: ts.Node) => {
    const kids = node.getChildren(sf);
    if (kids.length === 0) {
      add(ts.getLeadingCommentRanges(text, node.getFullStart()));
      add(ts.getTrailingCommentRanges(text, node.getEnd()));
      return;
    }
    for (const k of kids) walk(k);
  };
  walk(sf);
  return [...byPos.values()].sort((a, b) => a.pos - b.pos);
}

const offenders: string[] = [];
let scanned = 0;
let generated = 0;

for (const root of ROOTS)
for (const rel of new Glob("**/*.ts").scanSync(root)) {
  const abs = join(root, rel);
  const text = readFileSync(abs, "utf8");
  if (GENERATED.test(text)) {
    generated++;
    continue;
  }
  scanned++;
  const sf = ts.createSourceFile(rel, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  for (const r of commentRanges(sf, text)) {
    const body = text.slice(r.pos, r.end);
    if (r.pos === 0 && body.startsWith("#!")) continue;
    if (DIRECTIVE.test(body.trimStart())) continue;
    const line = sf.getLineAndCharacterOfPosition(r.pos).line + 1;
    const first = body.split("\n")[0].trim();
    offenders.push(`${relative(ROOT, abs)}:${line}  ${first.slice(0, 90)}`);
  }
}

function rustCommentStart(line: string): number {
  let inString = false;
  let inChar = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inString || inChar) {
      if (c === "\\") i++;
      else if (inString && c === '"') inString = false;
      else if (inChar && c === "'") inChar = false;
      continue;
    }
    if (c === '"') {
      inString = true;
    } else if (c === "'") {
      if (line[i + 2] === "'" || line[i + 1] === "\\") inChar = true;
    } else if (c === "/" && line[i + 1] === "/") {
      return i;
    }
  }
  return -1;
}

let rustScanned = 0;
for (const rel of new Glob("**/*.rs").scanSync(CLIENT)) {
  if (rel.startsWith("target/") || rel.includes("/target/")) continue;
  const abs = join(CLIENT, rel);
  const text = readFileSync(abs, "utf8");
  if (GENERATED.test(text)) continue;
  rustScanned++;

  const clap = CLAP_FILES.has(rel);
  text.split("\n").forEach((raw, i) => {
    const at = rustCommentStart(raw);
    if (at === -1) return;
    const body = raw.slice(at);
    const doc = body.startsWith("///") || body.startsWith("//!");
    if (doc && clap) return;
    if (!doc && RUST_DIRECTIVE.test(body.trim())) return;
    const why = doc ? "doc comments outside a clap file" : "line comments";
    offenders.push(`client/${rel}:${i + 1}  ${body.trim().slice(0, 80)}   (${why})`);
  });
}

if (offenders.length > 0) {
  console.error(`Comments are not allowed in daemon/. Found ${offenders.length}:\n`);
  for (const o of offenders) console.error(`  ${o}`);
  console.error(`\nSee CLAUDE.md. Rename something or write a test instead.`);
  console.error(`Directives (@ts-expect-error, eslint-*) and generated files are exempt.`);
  process.exit(1);
}

console.log(`no comments in ${scanned} ts and ${rustScanned} rust files (${generated} generated skipped)`);
